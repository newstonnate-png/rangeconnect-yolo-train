#!/usr/bin/env python3
"""Fetch the bullet-hole dataset onto the training instance.

Default source: Roboflow (env ROBOFLOW_API_KEY + workspace/project/version).
Dataset *export* is free on the Roboflow free tier — no paid plan needed.
Optional source: a private HuggingFace *dataset* repo (DATASET_SOURCE=hf,
env HF_DATASET_REPO, auth via HF_TOKEN).

Lands data at datasets/bullet-hole/{train,valid,test}/{images,labels} and
writes data/bullet-hole.yaml with absolute paths. If valid/ has no images,
make_val_split.py is invoked to carve one out of train/.

Env:
  DATASET_SOURCE        "roboflow" (default) | "hf"
  ROBOFLOW_API_KEY      required for roboflow
  ROBOFLOW_WORKSPACE    default "justines-workspace-ls3un"
  ROBOFLOW_PROJECT      default "justines-workspace-ls3un"
  ROBOFLOW_VERSION      default "1"
  ROBOFLOW_FORMAT       default "yolov8" (label format; yolov8/yolo11 are identical on disk)
  HF_DATASET_REPO       required for hf
  HF_TOKEN              auth for a private hf dataset repo
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEST = REPO_ROOT / "datasets" / "bullet-hole"
DATA_YAML = REPO_ROOT / "data" / "bullet-hole.yaml"
SCRIPTS = REPO_ROOT / "scripts"

IMG_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def _count_images(d: Path) -> int:
    if not d.exists():
        return 0
    return sum(1 for p in d.rglob("*") if p.suffix.lower() in IMG_EXTS)


def fetch_roboflow() -> None:
    from roboflow import Roboflow

    api_key = os.environ["ROBOFLOW_API_KEY"]
    ws = os.environ.get("ROBOFLOW_WORKSPACE", "justines-workspace-ls3un")
    proj = os.environ.get("ROBOFLOW_PROJECT", "justines-workspace-ls3un")
    ver = int(os.environ.get("ROBOFLOW_VERSION", "1"))
    fmt = os.environ.get("ROBOFLOW_FORMAT", "yolov8")
    print(f"[fetch] Roboflow {ws}/{proj} v{ver} as {fmt}")

    rf = Roboflow(api_key=api_key)
    dataset = (
        rf.workspace(ws).project(proj).version(ver).download(fmt, location=str(DEST))
    )
    print(f"[fetch] downloaded to {dataset.location}")


def fetch_hf() -> None:
    from huggingface_hub import snapshot_download

    repo = os.environ["HF_DATASET_REPO"]
    token = os.environ.get("HF_TOKEN")
    print(f"[fetch] HF dataset repo: {repo}")
    local = snapshot_download(
        repo_id=repo,
        repo_type="dataset",
        token=token,
        local_dir=str(DEST),
    )
    print(f"[fetch] downloaded to {local}")


def normalize_layout() -> None:
    """Make the tree predictable: datasets/bullet-hole/{train,valid,test}.

    Handles a single nested export folder and the 'val' vs 'valid' naming
    difference between exporters.
    """
    if not (DEST / "train").exists():
        for child in sorted(DEST.iterdir()):
            if child.is_dir() and (child / "train").exists():
                for sub in child.iterdir():
                    dst = DEST / sub.name
                    if dst.exists():
                        continue
                    shutil.move(str(sub), str(dst))
                shutil.rmtree(child, ignore_errors=True)
                break

    if (DEST / "val").exists() and not (DEST / "valid").exists():
        (DEST / "val").rename(DEST / "valid")

    for split in ("train", "valid", "test"):
        (DEST / split / "images").mkdir(parents=True, exist_ok=True)
        (DEST / split / "labels").mkdir(parents=True, exist_ok=True)


def write_data_yaml() -> None:
    DATA_YAML.parent.mkdir(parents=True, exist_ok=True)
    DATA_YAML.write_text(
        "# Auto-generated by scripts/fetch_dataset.py — do not edit by hand.\n"
        f"path: {DEST.as_posix()}\n"
        "train: train/images\n"
        "val: valid/images\n"
        "test: test/images\n"
        "nc: 1\n"
        "names: [bullet-hole]\n"
    )
    print(f"[fetch] wrote {DATA_YAML}")


def main() -> int:
    DEST.mkdir(parents=True, exist_ok=True)

    source = os.environ.get("DATASET_SOURCE", "roboflow").lower()
    if source == "roboflow":
        if not os.environ.get("ROBOFLOW_API_KEY"):
            print("ERROR: ROBOFLOW_API_KEY not set (DATASET_SOURCE=roboflow).", file=sys.stderr)
            return 1
        fetch_roboflow()
    elif source == "hf":
        if not os.environ.get("HF_DATASET_REPO"):
            print("ERROR: HF_DATASET_REPO not set (DATASET_SOURCE=hf).", file=sys.stderr)
            return 1
        fetch_hf()
    else:
        print(f"ERROR: unknown DATASET_SOURCE={source!r} (want 'roboflow' or 'hf').", file=sys.stderr)
        return 1

    normalize_layout()

    train_n = _count_images(DEST / "train" / "images")
    valid_n = _count_images(DEST / "valid" / "images")
    test_n = _count_images(DEST / "test" / "images")
    print(f"[fetch] images — train={train_n} valid={valid_n} test={test_n}")

    if train_n == 0:
        print("ERROR: no training images found after fetch.", file=sys.stderr)
        return 1

    if valid_n == 0:
        print("[fetch] no validation images — carving a split from train/")
        rc = subprocess.call([sys.executable, str(SCRIPTS / "make_val_split.py")])
        if rc != 0:
            return rc

    write_data_yaml()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
